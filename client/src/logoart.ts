const COLORS: Record<string, string> = { "#": "#ffffff", s: "#c9cfee" };

/**
 * Fit the logo to a screen `w` game pixels wide: 2x when it fits, else 1x, else (a very
 * narrow screen) whatever fits. Always centered where it's placed (origin in the middle).
 */
export function fitLogo(img: Phaser.GameObjects.Image, w: number) {
  const room = w - 16;
  img.setScale(img.width <= room ? 1 : img.width / 2 <= room ? 0.5 : room / img.width);
}

/** The logo as a texture (`scale` game pixels per logo pixel). */
export function buildPixelLogo(scene: Phaser.Scene, key: string, scale = 2) {
  if (scene.textures.exists(key)) scene.textures.remove(key);
  const w = ROWS[0].length;
  const h = ROWS.length;
  const tex = scene.textures.createCanvas(key, w * scale, h * scale)!;
  const ctx = tex.getContext();
  ROWS.forEach((row, y) => {
    for (let x = 0; x < w; x++) {
      const c = COLORS[row[x]];
      if (!c) continue;
      ctx.fillStyle = c;
      ctx.fillRect(x * scale, y * scale, scale, scale);
    }
  });
  tex.refresh();
}
